export function bigWidth(str, scale = 1) {
  return str.length * 6 * scale - scale;
}

// Dibuja con medios bloques (8 filas de píxel -> 4 filas de celda).
// colorFn(x, y) -> color por celda (permite brillos animados)
export function drawBigHalf(term, x0, y0, str, colorFn) {
  let x = x0;
  for (const ch of str.toUpperCase()) {
    const g = G[ch] || G[' '];
    for (let r = 0; r < 4; r++) {
      for (let c = 0; c < 5; c++) {
        const top = g[r * 2][c] === '#';
        const bot = g[r * 2 + 1][c] === '#';
        const glyph = top && bot ? '█' : top ? '▀' : bot ? '▄' : null;
        if (glyph) term.put(x + c, y0 + r, glyph, colorFn(x + c, y0 + r));
      }
    }
    x += 6;
  }
  return x - x0 - 1;
}

// Dibuja a escala completa: cada píxel = sx celdas de ancho x 1 fila. Con sombra.
export function drawBig(term, x0, y0, str, colorFn, opts = {}) {
  const sx = opts.sx || 2;
  const shadow = opts.shadow;
  const startRow = opts.skipTop ? 1 : 0;
  let x = x0;
  for (const ch of str.toUpperCase()) {
    const g = G[ch] || G[' '];
    for (let r = startRow; r < 8; r++) {
      for (let c = 0; c < 5; c++) {
        if (g[r][c] !== '#') continue;
        const yy = y0 + r - startRow;
        for (let k = 0; k < sx; k++) {
          const xx = x + c * sx + k;
          if (shadow) {
            const sh = term.get(xx + 1, yy + 1);
            if (sh && sh.ch === ' ') term.put(xx + 1, yy + 1, '▒', shadow);
          }
          term.put(xx, yy, '█', colorFn(xx, yy));
        }
      }
    }
    x += 6 * sx;
  }
  return x - x0 - sx;
}
